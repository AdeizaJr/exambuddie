async function main() {
  let total = 0;
  for (const [subjectCode, oldTopic, newTopic] of TOPIC_MAP) {
    const { rowCount } = await pool.query(
      `UPDATE did_you_know SET topic = $1 WHERE subject_code = $2 AND topic = $3`,
      [newTopic, subjectCode, oldTopic]
    );
    total += rowCount || 0;
  }
  console.log(`✅ Realigned ${total} did_you_know rows across ${TOPIC_MAP.length} topic mappings.`);
  process.exit(0);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
